    if (news) {
        renderNews(currentLang);
    }
    applyLanguage(currentLang);

    // === Event Listeners ===

    // Language toggle
    elements.langToggle?.addEventListener('click', (e) => {
        // Let the dropdown options (handled by i18n.js) switch to their own language
        if (e.target.closest('.lang-option, .lang-option-mobile')) return;
        e.preventDefault();
        currentLang = currentLang === 'ar' ? 'en' : 'ar';
        applyLanguage(currentLang);
    });

    // Back button
    elements.backBtn?.addEventListener('click', (e) => {
        e.preventDefault();
        // Preserve language when going back
        const referrer = document.referrer;
        if (referrer) {
            const url = new URL(referrer);
            url.hash = '#media';
            window.location.href = url.href;
        } else {
            window.location.href = `index.html?lang=${currentLang}#media`;
        }
    });

    // Handle browser back/forward
    window.addEventListener('popstate', () => {
        const savedLang = localStorage.getItem('siteLang');
        if (savedLang && savedLang !== currentLang) {
            currentLang = savedLang;
            applyLanguage(currentLang);
        }
    });

    // Listen for language changes from other pages
    document.addEventListener('languageChanged', (e) => {
        if (e.detail.lang !== currentLang) {
            currentLang = e.detail.lang;
            applyLanguage(currentLang);
        }
    });

